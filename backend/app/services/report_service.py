FONT_DIR = Path(__file__).resolve().parents[1] / "assets" / "fonts"
INK = HexColor("#1c2430")
MUTED = HexColor("#5c6670")
TEAL = HexColor("#0f5c59")
RULE = HexColor("#d5d0c8")
PAPER = HexColor("#f4f1eb")
NOTICE_BG = HexColor("#f8f1e3")
NOTICE_EDGE = HexColor("#c4a15a")
LINE_WIDTH = 92

_FONTS: tuple[str, str] | None = None


@dataclass
class ReportBlock:
    kind: str
    text: str = ""
    rows: list[tuple[str, str]] = field(default_factory=list)
    table: list[list[str]] = field(default_factory=list)


@dataclass
class ReportDocument:
    case_id: str
    generated_at: str
    evidence_text: str
    evidence_display: str
    blocks: list[ReportBlock]


def ensure_fonts() -> tuple[str, str]:
    """Register the bundled DejaVu fonts once and return sans and mono names."""
    global _FONTS
    if _FONTS is not None:
        return _FONTS
    sans_path = FONT_DIR / "DejaVuSans.ttf"
    mono_path = FONT_DIR / "DejaVuSansMono.ttf"
    if sans_path.is_file() and mono_path.is_file():
        pdfmetrics.registerFont(TTFont("DejaVu", str(sans_path)))
        pdfmetrics.registerFont(TTFont("DejaVuMono", str(mono_path)))
        _FONTS = ("DejaVu", "DejaVuMono")
        return _FONTS
    _FONTS = ("Helvetica", "Courier")
    return _FONTS


def _font_supports(font_name: str, character: str) -> bool:
    if character in "\n\r\t":
        return True
    font = pdfmetrics.getFont(font_name)
    face = getattr(font, "face", None)
    mapping = getattr(face, "charToGlyph", None)
    code = ord(character)
    if mapping is None:
        return code < 256
    glyph = mapping.get(code)
    return glyph not in (None, 0)


def sanitize_for_font(text: str, font_name: str) -> tuple[str, bool]:
    """Replace glyphs the report font cannot draw with visible code points."""
    replaced = False
    pieces: list[str] = []
    for character in text:
        if _font_supports(font_name, character):
            pieces.append(character)
            continue
        replaced = True
        pieces.append(f"[U+{ord(character):04X}]")
    return "".join(pieces), replaced


def wrap_display_text(text: str, width: int = LINE_WIDTH) -> tuple[str, bool]:
    """Wrap long lines for the page without changing the stored evidence."""
    wrapped = False
    lines: list[str] = []
    for line in text.split("\n"):
        if len(line) <= width:
            lines.append(line)
            continue
        wrapped = True
        lines.extend(line[index : index + width] for index in range(0, len(line), width))
    return "\n".join(lines), wrapped


def document_plaintext(document: ReportDocument) -> str:
    """Flatten a report document for tests and plain-text review."""
    parts: list[str] = []
    for block in document.blocks:
        if block.kind in {"heading", "paragraph", "notice", "mono"}:
            parts.append(block.text)
        elif block.kind == "kv":
            parts.extend(f"{label}: {value}" for label, value in block.rows)
        elif block.kind == "table":
            parts.extend(" | ".join(row) for row in block.table)
    return "\n".join(parts)


def _display_value(value: Any) -> str:
    if value is None or value == "":
        return "Not recorded"
    return str(value)


def build_report_document(
    case: dict[str, Any],
    events: list[dict[str, Any]],
    integrity: dict[str, Any],
    generated_at: str,
    mono_font: str,
) -> ReportDocument:
    """Assemble the advisory report from stored evidence and analysis."""
    evidence_text = case.get("original_content") or ""
    sanitized, replaced = sanitize_for_font(evidence_text, mono_font)
    evidence_display, wrapped = wrap_display_text(sanitized)
    blocks: list[ReportBlock] = [
        ReportBlock(
            "notice",
            (
                "This report is an advisory record produced by ScamShield AI. "
                "It does not prove that the submitted content is fraudulent, and "
                "it does not determine whether the content was written by a person "
                "or generated by AI. The SHA-256 digest can show whether the stored "
                "text still matches the digest recorded at collection. It does not "
                "by itself prove who collected the evidence or when it was collected. "
                "This application does not provide a certified chain of custody. "
                "The authoritative evidence is the stored original text."
            ),
        ),
        ReportBlock("heading", "Case"),
        ReportBlock(
            "kv",
            rows=[
                ("Case ID", _display_value(case.get("case_id"))),
                ("Evidence type", _display_value(case.get("evidence_type"))),
                ("Analysis status", _display_value(case.get("analysis_status"))),
                ("Analysis provider", _display_value(case.get("analysis_provider"))),
                ("Record created (UTC)", _display_value(case.get("created_at"))),
                (
                    "Evidence collected (UTC)",
                    _display_value(case.get("evidence_collected_at")),
                ),
                ("Report generated (UTC)", generated_at),
                ("Application version", config.APP_VERSION),
            ],
        ),
        ReportBlock("heading", "Evidence preservation"),
        ReportBlock(
            "kv",
            rows=[
                ("SHA-256", _display_value(case.get("evidence_sha256"))),
                ("Characters", str(len(evidence_text))),
                ("UTF-8 bytes", str(len(evidence_text.encode("utf-8")))),
            ],
        ),
        ReportBlock(
            "paragraph",
            (
                "The digest is the SHA-256 of the exact stored text encoded as "
                "UTF-8. Whitespace, casing, newlines, and Unicode are not normalized."
            ),
        ),
    ]
    if replaced or wrapped:
        notes = []
        if replaced:
            notes.append(
                "Some characters are shown as Unicode code points because the "
                "report font cannot draw them."
            )
        if wrapped:
            notes.append(
                "Long lines are wrapped for display. Wrapping does not change "
                "the stored evidence or its SHA-256 digest."
            )
        blocks.append(ReportBlock("paragraph", " ".join(notes)))

    blocks.append(ReportBlock("heading", "Submitted evidence"))
    blocks.append(ReportBlock("mono", evidence_display))
    blocks.extend(_analysis_blocks(case))
    blocks.append(ReportBlock("heading", "Integrity check"))
    blocks.append(
        ReportBlock(
            "kv",
            rows=[
                ("Integrity status", _display_value(integrity.get("integrity_status"))),
                ("Message", _display_value(integrity.get("message"))),
                ("Recorded SHA-256", _display_value(integrity.get("original_sha256"))),
                (
                    "Calculated SHA-256",
                    _display_value(integrity.get("calculated_sha256")),
                ),
                ("Verified at (UTC)", _display_value(integrity.get("verified_at"))),
            ],
        )
    )
    blocks.append(
        ReportBlock(
            "paragraph",
            (
                "This check was run while the report was generated. A FAILED "
                "result does not repair or overwrite the stored evidence."
            ),
        )
    )
    blocks.append(ReportBlock("heading", "Event history"))
    table = [["Time (UTC)", "Event", "Details"]]
    if events:
        for event in events:
            table.append(
                [
                    _display_value(event.get("event_timestamp")),
                    _display_value(event.get("event_type")),
                    _display_value(event.get("details")),
                ]
            )
    else:
        table.append(["Not recorded", "Not recorded", "No events are stored."])
    blocks.append(ReportBlock("table", table=table))
    blocks.append(
        ReportBlock(
            "paragraph",
            (
                "The SHA-256 of this PDF is stored in the investigation database "
                "and in the report-generation event. It is not printed inside the "
                "file, because embedding it would change the digest."
            ),
        )
    )
    return ReportDocument(
        case_id=str(case.get("case_id")),
        generated_at=generated_at,
        evidence_text=evidence_text,
        evidence_display=evidence_display,
        blocks=blocks,
    )


def _analysis_blocks(case: dict[str, Any]) -> list[ReportBlock]:
    blocks = [ReportBlock("heading", "Advisory analysis")]
    if not case.get("risk_level"):
        blocks.append(
            ReportBlock(
                "paragraph",
                "No advisory analysis is stored for this case. The submitted "
                "evidence remains preserved.",
            )
        )
        return blocks

    blocks.append(
        ReportBlock(
            "kv",
            rows=[
                ("Risk level", _display_value(case.get("risk_level"))),
                ("Scam type", _display_value(case.get("scam_type"))),
            ],
        )
    )
    blocks.append(ReportBlock("paragraph", _display_value(case.get("summary"))))
    if case.get("analysis_provider") == "mock":
        blocks.append(
            ReportBlock(
                "paragraph",
                "The mock provider did not assess the submitted content. This "
                "result is a labeled placeholder.",
            )
        )

    blocks.append(ReportBlock("heading", "Indicators"))
    indicators = case.get("indicators") or []
    if not indicators:
        blocks.append(ReportBlock("paragraph", "No indicators were recorded."))
    else:
        for index, indicator in enumerate(indicators, start=1):
            quote = indicator.get("evidence_quote") or ""
            explanation = indicator.get("explanation") or ""
            blocks.append(ReportBlock("paragraph", f"Indicator {index}"))
            blocks.append(ReportBlock("mono", quote))
            blocks.append(ReportBlock("paragraph", explanation))

    blocks.append(ReportBlock("heading", "Recommended actions"))
    actions = case.get("recommended_actions") or []
    if not actions:
        blocks.append(ReportBlock("paragraph", "No recommended actions were recorded."))
    else:
        for index, action in enumerate(actions, start=1):
            blocks.append(ReportBlock("paragraph", f"{index}. {action}"))

    blocks.append(ReportBlock("heading", "Limitations"))
    limitations = case.get("limitations") or []
    if not limitations:
        blocks.append(ReportBlock("paragraph", "No limitations were recorded."))
    else:
        for limitation in limitations:
            blocks.append(ReportBlock("paragraph", limitation))
    return blocks


def _styles(sans: str, mono: str) -> dict[str, ParagraphStyle]:
    return {
        "body": ParagraphStyle(
            "Body",
            fontName=sans,
            fontSize=9.5,
            leading=13,
            textColor=INK,
            alignment=TA_LEFT,
            spaceAfter=0,
        ),
        "label": ParagraphStyle(
            "Label",
            fontName=sans,
            fontSize=8,
            leading=11,
            textColor=MUTED,
        ),
        "value": ParagraphStyle(
            "Value",
            fontName=sans,
            fontSize=9,
            leading=12,
            textColor=INK,
        ),
        "heading": ParagraphStyle(
            "Heading",
            fontName=sans,
            fontSize=12,
            leading=15,
            textColor=TEAL,
            spaceBefore=0,
            spaceAfter=1,
        ),
        "notice": ParagraphStyle(
            "Notice",
            fontName=sans,
            fontSize=8.5,
            leading=12,
            textColor=INK,
        ),
        "mono": ParagraphStyle(
            "Mono",
            fontName=mono,
            fontSize=8,
            leading=11,
            textColor=INK,
        ),
        "table": ParagraphStyle(
            "TableCell",
            fontName=sans,
            fontSize=7.5,
            leading=10,
            textColor=INK,
        ),
        "table_head": ParagraphStyle(
            "TableHead",
            fontName=sans,
            fontSize=7.5,
            leading=10,
            textColor=white,
        ),
    }


def _xml(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def _mono_markup(text: str) -> str:
    escaped = _xml(text).replace("\t", "    ")
    escaped = escaped.replace(" ", "&nbsp;")
    return escaped.replace("\r\n", "\n").replace("\r", "\n").replace("\n", "<br/>")


def _paragraph(text: str, style: ParagraphStyle) -> Paragraph:
    markup = _xml(text).replace("\n", "<br/>")
    return Paragraph(markup or "&nbsp;", style)


def build_story(
    document: ReportDocument, sans: str, mono: str, width: float
) -> list[Any]:
    """Turn report blocks into ReportLab flowables."""
    styles = _styles(sans, mono)
    story: list[Any] = []
    for block in document.blocks:
        if block.kind == "heading":
            story.append(Spacer(1, 3.5 * mm))
            story.append(Paragraph(_xml(block.text), styles["heading"]))
            story.append(
                HRFlowable(width="100%", thickness=0.6, color=TEAL, spaceAfter=2 * mm)
            )
        elif block.kind == "paragraph":
            story.append(_paragraph(block.text, styles["body"]))
            story.append(Spacer(1, 2 * mm))
        elif block.kind == "notice":
            notice = Table(
                [[_paragraph(block.text, styles["notice"])]],
                colWidths=[width],
            )
            notice.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), NOTICE_BG),
                        ("BOX", (0, 0), (-1, -1), 0.8, NOTICE_EDGE),
                        ("LEFTPADDING", (0, 0), (-1, -1), 8),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                        ("TOPPADDING", (0, 0), (-1, -1), 8),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ]
                )
            )
            story.append(notice)
        elif block.kind == "kv":
            rows = [
                [
                    Paragraph(_xml(label), styles["label"]),
                    Paragraph(_xml(value), styles["value"]),
                ]
                for label, value in block.rows
            ]
            table = Table(rows, colWidths=[48 * mm, width - 48 * mm])
            table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), PAPER),
                        ("LINEBELOW", (0, 0), (-1, -2), 0.3, RULE),
                        ("LEFTPADDING", (0, 0), (-1, -1), 6),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ]
                )
            )
            story.append(table)
            story.append(Spacer(1, 2 * mm))
        elif block.kind == "mono":
            mono = Table(
                [[Paragraph(_mono_markup(block.text) or "&nbsp;", styles["mono"])]],
                colWidths=[width],
            )
            mono.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), PAPER),
                        ("BOX", (0, 0), (-1, -1), 0.4, RULE),
                        ("LEFTPADDING", (0, 0), (-1, -1), 8),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ]
                )
            )
            story.append(mono)
            story.append(Spacer(1, 2 * mm))
        elif block.kind == "table":
            header, *body = block.table
            data = [
                [Paragraph(_xml(cell), styles["table_head"]) for cell in header]
            ]
            data.extend(
                [Paragraph(_xml(cell), styles["table"]) for cell in row] for row in body
            )
            table = Table(data, colWidths=[42 * mm, 38 * mm, width - 80 * mm], repeatRows=1)
            commands: list[tuple[Any, ...]] = [
                ("BACKGROUND", (0, 0), (-1, 0), TEAL),
                ("TEXTCOLOR", (0, 0), (-1, 0), white),
                ("BACKGROUND", (0, 1), (-1, -1), white),
                ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
            if len(data) > 2:
                commands.append(("LINEBELOW", (0, 1), (-1, -2), 0.2, RULE))
            table.setStyle(TableStyle(commands))
            story.append(table)
    return story


def _paint_page(canvas: Any, doc: Any, document: ReportDocument, sans: str) -> None:
    canvas.saveState()
    width, height = A4
    canvas.setFillColor(TEAL)
    canvas.rect(0, height - 12 * mm, width, 12 * mm, fill=1, stroke=0)
    canvas.setFillColor(white)
    canvas.setFont(sans, 9)
    canvas.drawString(16 * mm, height - 7.5 * mm, "SCAMSHIELD AI")
    canvas.drawRightString(width - 16 * mm, height - 7.5 * mm, "Advisory forensic report")
    canvas.setFillColor(MUTED)
    canvas.setFont(sans, 8)
    canvas.drawString(
        16 * mm,
        8 * mm,
        "Not proof of fraud. Not a certified chain of custody.",
    )
    canvas.drawRightString(width - 16 * mm, 8 * mm, f"Page {doc.page}")
    canvas.restoreState()


def render_pdf(document: ReportDocument) -> bytes:
    """Render a report document to PDF bytes."""
    from io import BytesIO

    sans, mono = ensure_fonts()
    buffer = BytesIO()
    pdf = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=16 * mm,
        rightMargin=16 * mm,
        topMargin=18 * mm,
        bottomMargin=16 * mm,
        title=f"ScamShield AI report {document.case_id}",
        author="ScamShield AI",
        subject="Advisory scam-content investigation report",
    )
    story = build_story(document, sans, mono, pdf.width)

    def paint(canvas: Any, doc: Any) -> None:
        _paint_page(canvas, doc, document, sans)

    pdf.build(story, onFirstPage=paint, onLaterPages=paint)
    return buffer.getvalue()


def resolve_report_path(filename: str) -> Path | None:
    """Resolve a stored report name inside the reports directory."""
    if not filename or Path(filename).name != filename:
        return None
    root = Path(config.REPORTS_DIR).resolve()
    path = (root / filename).resolve()
    if path.parent != root:
        return None
    return path


def write_pdf(filename: str, pdf_bytes: bytes) -> Path:
    """Write a PDF atomically and return its path."""
    root = Path(config.REPORTS_DIR)
    root.mkdir(parents=True, exist_ok=True)
    target = root / filename
    temporary = target.with_suffix(".pdf.tmp")
    temporary.write_bytes(pdf_bytes)
    temporary.replace(target)
    return target


def generate_case_report(case_id: str) -> dict[str, Any] | None:
    """Verify evidence, render a PDF, and record the report. None if missing."""
    case = case_service.get_case(case_id)
    if case is None:
        return None

    integrity = case_service.verify_case(case_id)
    events = case_service.get_case_events(case_id) or []
    generated_at = get_utc_timestamp()
    _, mono = ensure_fonts()
    document = build_report_document(case, events, integrity or {}, generated_at, mono)
    pdf_bytes = render_pdf(document)
    report_id = str(uuid4())
    filename = f"{report_id}.pdf"
    digest = hashlib.sha256(pdf_bytes).hexdigest()
    path = write_pdf(filename, pdf_bytes)
    try:
        record = case_service.record_report(
            report_id=report_id,
            case_id=case_id,
            filename=filename,
            content_sha256=digest,
            generated_at=generated_at,
        )
    except Exception:
        path.unlink(missing_ok=True)
        raise
    if record is None:
        path.unlink(missing_ok=True)
        return None
    record["integrity_status"] = (integrity or {}).get("integrity_status")
    return record
